import { createHmac, timingSafeEqual, randomBytes } from 'node:crypto';
import { performance } from 'node:perf_hooks';
import { decodeHostTransferFrame, HOST_TRANSFER_MAX_CODE_UNITS } from './HostTransferFrame.mjs';

// Node-only trusted parent integration. This is deliberately NOT imported by
// browser/engine-neutral simulator code. The peer handle is the exact owned
// ChildProcess object, not a reusable PID, window title or untrusted label.
const SESSION = /^[a-f0-9]{32}$/;
const SECRET = /^[a-f0-9]{64}$/;
const MAC = /^[a-f0-9]{64}$/;
const SEQUENCE = /^[1-9][0-9]{0,15}$/;
const BASE64 = /^[A-Za-z0-9_-]+$/;
const MAX_ENVELOPE = Math.ceil(HOST_TRANSFER_MAX_CODE_UNITS * 4 * 4 / 3) + 256;
const PREFIX = 'FEAR-IPC-1';

function validSecret(secret) {
    if (typeof secret !== 'string' || !SECRET.test(secret))
        throw new Error('invalid trusted IPC credential');
}
function validSession(sessionId) {
    if (typeof sessionId !== 'string' || !SESSION.test(sessionId))
        throw new Error('invalid trusted IPC session');
}
function macFor(secret, signed) {
    return createHmac('sha256', Buffer.from(secret, 'hex'))
        .update(signed, 'utf8').digest('hex');
}
function boundedInteger(value, low, high, label) {
    if (!Number.isSafeInteger(value) || value < low || value > high)
        throw new Error('invalid trusted IPC ' + label);
    return value;
}
function allowList(values, label) {
    if (!Array.isArray(values) || values.length > 256 ||
        values.some(v => typeof v !== 'string' || v.length === 0 || v.length > 256))
        throw new Error('invalid trusted IPC ' + label);
    return new Set(values);
}

// Credentials must be generated by the trusted owner and shared only with
// the explicitly authorized child via a separate protected bootstrap channel.
// Possessing the secret permits only the peer's configured event/cargo scope.
export function createHostIpcCredential() {
    return Object.freeze({
        sessionId: randomBytes(16).toString('hex'),
        secret: randomBytes(32).toString('hex')
    });
}

// Authorized child-side helper: no reflection over host metadata. The caller
// supplies an already serialized primitive string; never call stringify here.
export function makeAuthenticatedHostMessage({ frame, sequence, sessionId, secret }) {
    validSecret(secret);
    validSession(sessionId);
    boundedInteger(sequence, 1, Number.MAX_SAFE_INTEGER, 'sequence');
    if (typeof frame !== 'string' || frame.length === 0 ||
        frame.length > HOST_TRANSFER_MAX_CODE_UNITS)
        throw new Error('invalid trusted IPC frame length');
    const payload = Buffer.from(frame, 'utf8').toString('base64url');
    const signed = [PREFIX, sessionId, String(sequence), payload].join('.');
    return signed + '.' + macFor(secret, signed);
}

export class AuthenticatedHostIpcGateway {
    #target;
    #capability;
    #peers = new Map();
    #clock;

    constructor(target, { clock = () => performance.now() } = {}) {
        if (!target || typeof target.sealHostTransferIngress !== 'function' ||
            typeof target.acceptHostTransferFrame !== 'function')
            throw new Error('trusted simulator or authority required');
        if (typeof clock !== 'function') throw new Error('invalid trusted IPC clock');
        // Seals even the public raw transfer API; the opaque Symbol only lives
        // in trusted code. No untrusted child receives this capability.
        this.#capability = target.sealHostTransferIngress();
        this.#target = target;
        this.#clock = clock;
    }

    registerPeer(peer, {
        peerId, secret, sessionId, allowedEventTypes = [],
        allowedEntityIds = [], maxMessagesPerWindow = 32, windowMs = 1000
    } = {}) {
        if (!peer || typeof peer !== 'object' || this.#peers.has(peer))
            throw new Error('invalid or duplicate owned IPC peer');
        if (typeof peerId !== 'string' || peerId.length < 1 || peerId.length > 128)
            throw new Error('invalid trusted IPC peer ID');
        validSecret(secret);
        validSession(sessionId);
        boundedInteger(maxMessagesPerWindow, 1, 1024, 'rate capacity');
        boundedInteger(windowMs, 10, 60000, 'rate window');
        if ([...this.#peers.values()].some(p => p.peerId === peerId ||
            p.sessionId === sessionId))
            throw new Error('duplicate trusted IPC identity or session');
        const state = {
            peerId, secret, sessionId,
            eventTypes: allowList(allowedEventTypes, 'event permissions'),
            entityIds: allowList(allowedEntityIds, 'entity permissions'),
            maxMessagesPerWindow, windowMs,
            lastSequence: 0, windowStart: null, lastNow: 0,
            attempts: 0, admitted: 0, accepted: 0, rejected: 0
        };
        this.#peers.set(peer, state);
        return Object.freeze({ peerId, sessionId });
    }

    revokePeer(peer) {
        return this.#peers.delete(peer);
    }

    // Trusted parent-only attachment. This wires only the explicit child
    // handle we created/own, and never searches by a PID or window title.
    attachChildProcess(child, registration, { onResult } = {}) {
        if (!child || typeof child.on !== 'function' ||
            typeof child.once !== 'function' ||
            (onResult !== undefined && typeof onResult !== 'function'))
            throw new Error('trusted ChildProcess handle required');
        const identity = this.registerPeer(child, registration);
        child.on('message', message => {
            const result = this.receiveFrom(child, message);
            if (onResult) onResult(result);
        });
        child.once('exit', () => this.revokePeer(child));
        child.once('disconnect', () => this.revokePeer(child));
        // ChildProcess 'error' without a listener would otherwise terminate
        // the trusted parent. Invalid/spawn-failed peers lose their authority.
        child.once('error', () => this.revokePeer(child));
        return identity;
    }

    #window(state) {
        const measured = this.#clock(); // trusted monotonic local clock only
        if (typeof measured !== 'number' || !Number.isFinite(measured) || measured < 0)
            throw new Error('invalid trusted IPC clock reading');
        const now = Math.max(measured, state.lastNow);
        state.lastNow = now;
        if (state.windowStart === null || now - state.windowStart >= state.windowMs) {
            state.windowStart = now;
            state.attempts = 0;
            state.admitted = 0;
        }
        return state;
    }

    receiveFrom(peer, message) {
        const state = this.#peers.get(peer); // no reflection on caller object
        if (!state) return Object.freeze({ accepted: false, reason: 'unknown_peer' });
        this.#window(state);
        // Bound pre-auth work too: malformed frames and forged MAC floods
        // cannot force unlimited HMAC/parse operations during a window.
        state.attempts++;
        const reject = reason => {
            state.rejected++;
            return Object.freeze({ accepted: false, reason });
        };
        if (state.attempts > state.maxMessagesPerWindow * 8 + 8)
            return reject('rate_limited');
        if (typeof message !== 'string' || message.length > MAX_ENVELOPE)
            return reject('invalid_envelope');
        const fields = message.split('.');
        if (fields.length !== 5 || fields[0] !== PREFIX ||
            fields[1] !== state.sessionId || !SEQUENCE.test(fields[2]) ||
            !BASE64.test(fields[3]) || !MAC.test(fields[4]))
            return reject('invalid_envelope');
        const seq = Number(fields[2]);
        if (!Number.isSafeInteger(seq)) return reject('invalid_envelope');
        const signed = fields.slice(0, 4).join('.');
        const expected = Buffer.from(macFor(state.secret, signed), 'hex');
        const provided = Buffer.from(fields[4], 'hex');
        if (provided.length !== expected.length || !timingSafeEqual(provided, expected))
            return reject('unauthenticated');
        // Exact increment prevents both duplicates and out-of-order frames;
        // fresh credential+session on every owned child/process restart.
        if (seq !== state.lastSequence + 1) return reject('replay_or_sequence');
        if (state.admitted >= state.maxMessagesPerWindow)
            return reject('rate_limited');
        state.lastSequence = seq;
        state.admitted++;
        let wire;
        try {
            const raw = Buffer.from(fields[3], 'base64url');
            wire = new TextDecoder('utf-8', { fatal: true }).decode(raw);
            if (wire.length > HOST_TRANSFER_MAX_CODE_UNITS)
                return reject('invalid_payload');
            const frame = decodeHostTransferFrame(wire);
            if (frame.kind === 'event') {
                if (!state.eventTypes.has(frame.type)) return reject('forbidden_event');
            } else if (!state.entityIds.has(frame.entityId)) {
                return reject('forbidden_entity');
            }
            const receipt = this.#target.acceptHostTransferFrame(
                wire, this.#capability);
            state.accepted++;
            return Object.freeze({ accepted: true, receipt });
        } catch {
            // Do not leak crypto/signature/parse internals through the wire.
            return reject('invalid_payload');
        }
    }

    getPeerStats(peer) {
        const state = this.#peers.get(peer);
        if (!state) return null;
        return Object.freeze({
            peerId: state.peerId, lastSequence: state.lastSequence,
            accepted: state.accepted, rejected: state.rejected,
            admittedInWindow: state.admitted, attemptsInWindow: state.attempts
        });
    }
}

export function createAuthenticatedHostIpcGateway(target, options) {
    return new AuthenticatedHostIpcGateway(target, options);
}
